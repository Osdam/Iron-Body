    public static Dictionary<char, byte> BuildReverse(ushort[] high)
    {
        if (high.Length != 128)
        {
            throw new InvalidOperationException("Una tabla de página de códigos debe cubrir exactamente 0x80–0xFF.");
        }

        var map = new Dictionary<char, byte>(128);
        for (var i = 0; i < high.Length; i++)
        {
            map[(char)high[i]] = (byte)(0x80 + i);
        }

        return map;
    }
